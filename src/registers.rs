impl TryFrom<u8> for IoRegister {
    type Error = ();

    fn try_from(b: u8) -> Result<Self, Self::Error> {
        let reg = match b {
            0x00 => Self::JOYP,
            0x01 => Self::SB,
            0x02 => Self::SC,
            0x04 => Self::DIV,
            0x05 => Self::TIMA,
            0x06 => Self::TMA,
            0x07 => Self::TAC,
            0x0f => Self::IF,
            0x10 => Self::NR10,
            0x11 => Self::NR11,
            0x12 => Self::NR12,
            0x13 => Self::NR13,
            0x14 => Self::NR14,
            0x16 => Self::NR21,
            0x17 => Self::NR22,
            0x18 => Self::NR23,
            0x19 => Self::NR24,
            0x1a => Self::NR30,
            0x1b => Self::NR31,
            0x1c => Self::NR32,
            0x1d => Self::NR33,
            0x1e => Self::NR34,
            0x20 => Self::NR41,
            0x21 => Self::NR42,
            0x22 => Self::NR43,
            0x23 => Self::NR44,
            0x24 => Self::NR50,
            0x25 => Self::NR51,
            0x26 => Self::NR52,
            0x30..=0x3f => Self::WaveRAM(b - 0x30),
            0x40 => Self::LCDC,
            0x41 => Self::STAT,
            0x42 => Self::SCY,
            0x43 => Self::SCX,
            0x44 => Self::LY,
            0x45 => Self::LYC,
            0x46 => Self::DMA,
            0x47 => Self::BGP,
            0x48 => Self::OBP0,
            0x49 => Self::OBP1,
            0x4a => Self::WY,
            0x4b => Self::WX,
            0x4c => Self::KEY0,
            0x4d => Self::KEY1,
            0x4f => Self::VBK,
            0x50 => Self::BANK,
            0x51 => Self::HDMA1,
            0x52 => Self::HDMA2,
            0x53 => Self::HDMA3,
            0x54 => Self::HDMA4,
            0x55 => Self::HDMA5,
            0x56 => Self::RP,
            0x68 => Self::BCPS,
            0x69 => Self::BCPD,
            0x6a => Self::OCPS,
            0x6b => Self::OCPD,
            0x6c => Self::OPRI,
            0x70 => Self::SVBK,
            0x76 => Self::PCM12,
            0x77 => Self::PCM34,
            _ => return Err(()),
        };

        Ok(reg)
    }
}

